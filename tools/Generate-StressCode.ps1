param(
    [switch]$Check,
    [string]$NativeTools = 'C:\Users\Ubehage\Documents\WinLibs\mingw64\bin'
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$nasm = Join-Path $NativeTools 'nasm.exe'
if (-not (Test-Path -LiteralPath $nasm -PathType Leaf)) { throw "NASM not found: $nasm" }
$outputPath = Join-Path $root 'build\stress-code'
New-Item -ItemType Directory -Force -Path $outputPath | Out-Null
$manifest = [ordered]@{
    StressWOW64GateHex = 'wow64-gate'
    StressFMA64Hex = 'fma64'
    StressAVX64Hex = 'avx64'
    StressSSE64Hex = 'sse64'
    StressSSE32Hex = 'sse32'
    StressLegacy32Hex = 'legacy32'
}
$generated = New-Object 'System.Collections.Generic.List[string]'
$generated.Add('Attribute VB_Name = "modStressCode"')
$generated.Add('Option Explicit')
$generated.Add('')
$generated.Add("' Generated by tools/Generate-StressCode.ps1 from stress-kernels/*.asm.")
$generated.Add("' Edit assembly source, regenerate, then run the generator with -Check.")
$generated.Add("' Hex comes from NASM binaries; adjacent comments are the corresponding source.")
$generated.Add("' All code is embedded: production requires no external ASM/BIN/HEX files.")
foreach ($entry in $manifest.GetEnumerator()) {
    $asmPath = Join-Path $root ('stress-kernels\' + $entry.Value + '.asm')
    $binPath = Join-Path $outputPath ($entry.Value + '.bin')
    $listingPath = Join-Path $outputPath ($entry.Value + '.lst')
    & $nasm -f bin -Wall -Werror -l $listingPath -o $binPath $asmPath
    if ($LASTEXITCODE -ne 0) { throw "NASM failed for $asmPath" }
    $bytes = [IO.File]::ReadAllBytes($binPath)
    $sourceLines = [IO.File]::ReadAllLines($asmPath)
    $offsets = @{}
    foreach ($listingLine in [IO.File]::ReadAllLines($listingPath)) {
        # A source statement can span several listing lines. Its first offset
        # identifies its entire range in the actual assembled binary, including
        # NASM-resolved relative displacements and alignment padding.
        if ($listingLine -match '^\s*(\d+)\s+([0-9A-Fa-f]{8})\s+[0-9A-Fa-f]') {
            $sourceLineNumber = [int]$Matches[1]
            if (-not $offsets.ContainsKey($sourceLineNumber)) {
                $offsets[$sourceLineNumber] = [Convert]::ToInt32($Matches[2], 16)
            }
        }
    }
    $orderedLines = @($offsets.Keys | Sort-Object)
    if ($orderedLines.Count -eq 0 -or $offsets[$orderedLines[0]] -ne 0) {
        throw "Cannot map NASM listing to binary: $asmPath"
    }
    $lengths = @{}
    for ($index = 0; $index -lt $orderedLines.Count; $index++) {
        $currentLine = $orderedLines[$index]
        $startOffset = $offsets[$currentLine]
        $endOffset = $bytes.Length
        if ($index + 1 -lt $orderedLines.Count) { $endOffset = $offsets[$orderedLines[$index + 1]] }
        if ($endOffset -le $startOffset) { throw "Invalid NASM listing offsets in $asmPath" }
        $lengths[$currentLine] = $endOffset - $startOffset
    }
    $generated.Add('')
    $generated.Add('Public Function ' + $entry.Key + '() As String')
    $generated.Add('    Dim Code As String')
    $emitted = 0
    for ($index = 0; $index -lt $sourceLines.Length; $index++) {
        $lineNumber = $index + 1
        $sourceText = $sourceLines[$index].Trim()
        if ($offsets.ContainsKey($lineNumber)) {
            $startOffset = $offsets[$lineNumber]
            $byteLength = $lengths[$lineNumber]
            for ($part = 0; $part -lt $byteLength; $part += 24) {
                $partLength = [Math]::Min(24, $byteLength - $part)
                $hexBytes = for ($byteIndex = 0; $byteIndex -lt $partLength; $byteIndex++) {
                    $bytes[$startOffset + $part + $byteIndex].ToString('X2')
                }
                $comment = $sourceText
                if ($part -ne 0) { $comment = 'continued bytes: ' + $sourceText }
                $generated.Add('    Code = Code & " ' + ($hexBytes -join ' ') + '" ' + "' " + $comment)
                $emitted += $partLength
            }
        } elseif ($sourceText.Length -gt 0) {
            $generated.Add("    ' " + $sourceText)
        }
    }
    if ($emitted -ne $bytes.Length) { throw "Incomplete byte emission for $asmPath" }
    $generated.Add('    ' + $entry.Key + ' = Mid$(Code, 2)')
    $generated.Add('End Function')
    Write-Output ($entry.Key + ': ' + $bytes.Length + ' bytes')
}
$content = ($generated -join "`r`n") + "`r`n"
$modulePath = Join-Path $root 'modStressCode.bas'
$encoding = [Text.Encoding]::GetEncoding(1252)
if ($Check) {
    if (-not (Test-Path -LiteralPath $modulePath -PathType Leaf)) { throw 'modStressCode.bas is missing; regenerate it first.' }
    if ([IO.File]::ReadAllText($modulePath, $encoding) -cne $content) {
        throw 'modStressCode.bas differs from the assembled kernels or source comments. Run tools/Generate-StressCode.ps1.'
    }
    Write-Output 'Embedded stress bytes and assembly comments match all six NASM sources.'
} else {
    [IO.File]::WriteAllText($modulePath, $content, $encoding)
    Write-Output "Generated $modulePath"
}
